"""
Run every query in sql/analysis/ against data/clt_flights.db, print the
results, and save them all to results/REPORT.md (which renders nicely on GitHub).

    python run_queries.py              # run everything
    python run_queries.py 03 05        # run only queries whose file name starts with 03 or 05
    python run_queries.py --sql "SELECT COUNT(*) FROM flights WHERE dest = 'LGA'"
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DB_PATH = ROOT / "data" / "clt_flights.db"
QUERY_DIR = ROOT / "sql" / "analysis"
REPORT = ROOT / "results" / "REPORT.md"


def run(con, sql: str):
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    return cols, cur.fetchall()


def fmt(v):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:,.1f}" if abs(v) < 1e6 else f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def console_table(cols, rows) -> str:
    cells = [[fmt(v) for v in r] for r in rows]
    widths = [max(len(c), *(len(r[i]) for r in cells)) if cells else len(c) for i, c in enumerate(cols)]
    line = "  ".join(c.ljust(w) for c, w in zip(cols, widths))
    out = [line, "  ".join("-" * w for w in widths)]
    out += ["  ".join(v.rjust(w) if v[:1].isdigit() or v[:1] == "-" else v.ljust(w) for v, w in zip(r, widths)) for r in cells]
    return "\n".join(out)


def markdown_table(cols, rows) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def title_of(sql: str, fallback: str) -> str:
    for line in sql.splitlines():
        if line.startswith("--"):
            return line.lstrip("- ").strip()
    return fallback


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("only", nargs="*", help="prefixes of query files to run")
    ap.add_argument("--sql", help="run one ad-hoc query instead")
    args = ap.parse_args()

    if not DB_PATH.exists():
        sys.exit("No database yet. Run: python load_data.py")
    con = sqlite3.connect(DB_PATH)

    if args.sql:
        print(console_table(*run(con, args.sql)))
        return

    files = sorted(QUERY_DIR.glob("*.sql"))
    if args.only:
        files = [f for f in files if any(f.name.startswith(p) for p in args.only)]

    md = ["# CLT flight delay analysis", "",
          "Generated by `run_queries.py` from U.S. DOT / BTS on-time performance data. "
          "Each section is one file in `sql/analysis/`.", ""]
    for f in files:
        sql = f.read_text(encoding="utf-8")
        title = title_of(sql, f.stem)
        cols, rows = run(con, sql)
        print(f"\n== {f.name}: {title}\n")
        print(console_table(cols, rows))
        md += [f"## {title}", "", f"[`{f.name}`](../sql/analysis/{f.name})", "", markdown_table(cols, rows), ""]

    if not args.only:
        REPORT.parent.mkdir(exist_ok=True)
        REPORT.write_text("\n".join(md), encoding="utf-8")
        print(f"\nSaved {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
